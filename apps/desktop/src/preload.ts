/** The recorder window's bridge to the main process (contextIsolation on). */
import { contextBridge, ipcRenderer } from "electron";

contextBridge.exposeInMainWorld("lensDesktop", {
  sources: () => ipcRenderer.invoke("lens:sources"),
  captureSource: (id: string, opts?: unknown) => ipcRenderer.invoke("lens:capture-source", id, opts),
  pickRegion: (displayId?: string) => ipcRenderer.invoke("lens:pick-region", displayId),
  teleprompter: () => ipcRenderer.invoke("lens:teleprompter"),
  history: () => ipcRenderer.invoke("lens:history"),
  historyOpen: (dir: string) => ipcRenderer.invoke("lens:history-open", dir),
  historyReveal: (dir: string) => ipcRenderer.invoke("lens:history-reveal", dir),
  historyDelete: (dir: string) => ipcRenderer.invoke("lens:history-delete", dir),
  importVideo: (file?: string) => ipcRenderer.invoke("lens:import", file),
  importCancel: () => ipcRenderer.invoke("lens:import-cancel"),
  onImportProgress: (fn: (p: unknown) => void) => ipcRenderer.on("lens:import-progress", (_e, p) => fn(p)),
  settingsGet: () => ipcRenderer.invoke("lens:settings-get"),
  settingsSet: (s: unknown) => ipcRenderer.invoke("lens:settings-set", s),
  settingsPickDir: (current: string) => ipcRenderer.invoke("lens:settings-pick-dir", current),
  settingsOpen: () => ipcRenderer.invoke("lens:settings-open"),
  onSettings: (fn: (s: unknown) => void) => ipcRenderer.on("lens:settings", (_e, s) => fn(s)),
  onMode: (fn: (m: string) => void) => ipcRenderer.on("lens:mode", (_e, m) => fn(m)),
  regionDone: (r: unknown) => ipcRenderer.send("lens:region-done", r),
  status: () => ipcRenderer.invoke("lens:status"),
  begin: () => ipcRenderer.invoke("lens:begin"),
  started: (info: unknown) => ipcRenderer.invoke("lens:started", info),
  chunk: (kind: "video" | "audio", data: ArrayBuffer) => ipcRenderer.send("lens:chunk", kind, data),
  stop: (opts?: { stopAt?: number }) => ipcRenderer.invoke("lens:stop", opts),
  abort: () => ipcRenderer.invoke("lens:abort"),
  openEditor: (dir: string) => ipcRenderer.invoke("lens:open-editor", dir),
  onToggle: (fn: () => void) => ipcRenderer.on("lens:toggle", () => fn()),
  onLive: (fn: (b: unknown) => void) => ipcRenderer.on("lens:live", (_e, b) => fn(b)),
  updateState: () => ipcRenderer.invoke("lens:update-state"),
  updateCheck: () => ipcRenderer.invoke("lens:update-check"),
  updateDownload: () => ipcRenderer.invoke("lens:update-download"),
  updateInstall: () => ipcRenderer.invoke("lens:update-install"),
  onUpdate: (fn: (s: unknown) => void) => ipcRenderer.on("lens:update", (_e, s) => fn(s)),
  onFinalizing: (fn: (stage: string) => void) => ipcRenderer.on("lens:finalizing", (_e, s) => fn(s)),
});
