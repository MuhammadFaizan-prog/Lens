/**
 * Music bed with automatic ducking (demand #23). Lens's own design (clean room, Rules.md §1).
 *
 * The music plays on the OUTPUT clock (it does not follow cuts: a bed runs under the whole video),
 * from `startMs` into the file, looped when the file is shorter than the video. Its gain is the
 * product of three things, all computed here so the preview (Web Audio) and the in-app export
 * (server/exportAudio.ts) apply exactly the same numbers:
 *
 *   1. level: the music is put `volumeDb` under the speech, measured as integrated loudness
 *      (loudness.ts) of what it is mixed with, so "-14 dB" means the same in any recording;
 *   2. duck: a piecewise-linear envelope from the speech ranges (the mic's measured voiced ranges, or
 *      the transcript's words), mapped onto the output clock: it starts going down `attackMs` before
 *      the speech (the whole recording is known, so the duck can look ahead), sits `depthDb` lower
 *      while the speech runs, holds `holdMs` after it and comes back up over `releaseMs`; a gap too
 *      short to come all the way back stays ducked (no pumping);
 *   3. fades: linear fade in at the start and fade out at the end of the video.
 *
 * Projects without `audio.music` have no `music` in the plan, so their plans are byte-identical.
 */
import type { TimeRange, Word } from "./types.js";

export interface MusicDuck {
  enabled: boolean;
  /** How far the music goes down under speech, dB (0..40). */
  depthDb: number;
  /** Ramp down, ms, ending where the speech starts (look-ahead). */
  attackMs: number;
  /** Stay down after the speech ends, ms. */
  holdMs: number;
  /** Ramp back up, ms. */
  releaseMs: number;
}

export interface MusicSettings {
  /** Bundle-relative file (music/<name>), or an absolute path in an export project. */
  path: string;
  /** Shown in the editor. */
  name: string;
  /** "file" = imported by the user; "builtin:<id>" = generated by Lens (musicBed.ts, CC0). */
  source: string;
  /** Off = muted but kept. */
  enabled: boolean;
  /** Music level relative to the speech when not ducked, dB (-40..+6). */
  volumeDb: number;
  duck: MusicDuck;
  fadeInMs: number;
  fadeOutMs: number;
  loop: boolean;
  /** Where in the file the music starts, ms. */
  startMs: number;
}

export function defaultMusicDuck(): MusicDuck {
  return { enabled: true, depthDb: 12, attackMs: 150, holdMs: 150, releaseMs: 600 };
}

export function defaultMusic(path = "", name = "", source = "file"): MusicSettings {
  return { path, name, source, enabled: true, volumeDb: -14, duck: defaultMusicDuck(), fadeInMs: 1000, fadeOutMs: 2000, loop: true, startMs: 0 };
}

/** Fill the fields a hand-written or older music block leaves out. */
export function normalizeMusic(m: Partial<MusicSettings> & { path: string }): MusicSettings {
  const d = defaultMusic(m.path, m.name ?? "", m.source ?? "file");
  return { ...d, ...m, duck: { ...d.duck, ...(m.duck ?? {}) } };
}

export function validateMusic(m: unknown): string[] {
  if (m === undefined || m === null) return [];
  const e: string[] = [];
  const x = m as MusicSettings;
  if (typeof x !== "object") return ["audio.music must be an object"];
  if (typeof x.path !== "string" || !x.path) e.push("audio.music.path is required");
  const num = (v: unknown, lo: number, hi: number) => typeof v === "number" && Number.isFinite(v) && v >= lo && v <= hi;
  if (!num(x.volumeDb, -60, 12)) e.push("audio.music.volumeDb must be within -60..12");
  if (!num(x.fadeInMs, 0, 60000) || !num(x.fadeOutMs, 0, 60000)) e.push("audio.music fades must be within 0..60000 ms");
  if (!num(x.startMs, 0, 24 * 3600 * 1000)) e.push("audio.music.startMs must be >= 0");
  const d = x.duck;
  if (!d || typeof d !== "object") e.push("audio.music.duck is required");
  else {
    if (!num(d.depthDb, 0, 60)) e.push("audio.music.duck.depthDb must be within 0..60");
    if (!num(d.attackMs, 0, 5000) || !num(d.holdMs, 0, 5000) || !num(d.releaseMs, 0, 10000)) e.push("audio.music.duck attack / hold / release out of range");
  }
  return e;
}

/** Piecewise-linear gain keys [tMs, gain] on the output clock; before the first / after the last key the end values hold. */
export type GainKey = [number, number];

export interface MusicPlan {
  path: string;
  /** Level relative to the speech, dB (the engine does not know loudness; the players measure it). */
  volumeDb: number;
  loop: boolean;
  startMs: number;
  /** Speech on the output clock (what the music ducks under). */
  speech: TimeRange[];
  /** Duck envelope (1 = full level). Empty = constant 1. */
  duck: GainKey[];
  /** Fade envelope (0 -> 1 -> 0). */
  fade: GainKey[];
}

/** Value of a piecewise-linear envelope at t (empty = 1). */
export function keyAt(keys: GainKey[], t: number): number {
  if (!keys.length) return 1;
  if (t <= keys[0]![0]) return keys[0]![1];
  for (let i = 1; i < keys.length; i++) {
    const [t1, g1] = keys[i]!;
    if (t <= t1) {
      const [t0, g0] = keys[i - 1]!;
      return t1 > t0 ? g0 + ((g1 - g0) * (t - t0)) / (t1 - t0) : g1;
    }
  }
  return keys[keys.length - 1]![1];
}

/** Music gain multiplier at output time t from the plan (duck x fade; the loudness level is applied by the player). */
export function musicEnvelopeAt(m: Pick<MusicPlan, "duck" | "fade">, t: number): number {
  return keyAt(m.duck, t) * keyAt(m.fade, t);
}

function merge(r: TimeRange[], gap = 0): TimeRange[] {
  const s = [...r].sort((a, b) => a.startMs - b.startMs);
  const out: TimeRange[] = [];
  for (const x of s) {
    const last = out[out.length - 1];
    if (last && x.startMs <= last.endMs + gap) last.endMs = Math.max(last.endMs, x.endMs);
    else out.push({ ...x });
  }
  return out;
}

/**
 * Speech on the recording clock. Measured silences (Transcript.pauses or the mic's silencedetect
 * ranges) are the reliable source: speech is what lies between them. Without them the transcript's
 * words are used (merged across gaps under 300 ms). Neither: no speech known.
 */
export function speechRanges(durationMs: number, words: Word[], pauses?: TimeRange[]): TimeRange[] {
  if (pauses) {
    const out: TimeRange[] = [];
    let t = 0;
    for (const p of merge(pauses)) {
      if (p.startMs > t) out.push({ startMs: t, endMs: Math.min(durationMs, p.startMs) });
      t = Math.max(t, p.endMs);
    }
    if (t < durationMs) out.push({ startMs: t, endMs: durationMs });
    return out.filter((r) => r.endMs - r.startMs >= 1);
  }
  if (words.length) return merge(words.map((w) => ({ startMs: w.startMs, endMs: w.endMs })), 300);
  return [];
}

/** Map source-clock speech through the audio pieces (cuts dropped, speed ranges compressed) onto the output clock. */
export function speechToOutput(pieces: Array<{ srcStart: number; srcEnd: number; outStart: number; rate: number }>, speech: TimeRange[]): TimeRange[] {
  const out: TimeRange[] = [];
  for (const p of pieces) {
    for (const s of speech) {
      const a = Math.max(p.srcStart, s.startMs);
      const b = Math.min(p.srcEnd, s.endMs);
      if (b <= a) continue;
      out.push({ startMs: p.outStart + (a - p.srcStart) / p.rate, endMs: p.outStart + (b - p.srcStart) / p.rate });
    }
  }
  return merge(out, 1).map((r) => ({ startMs: r2(r.startMs), endMs: r2(r.endMs) }));
}

const r2 = (n: number) => Math.round(n * 100) / 100;

/** The duck envelope for speech on the output clock (see the file comment). */
export function duckKeys(speech: TimeRange[], durationMs: number, d: MusicDuck): GainKey[] {
  if (!d.enabled || d.depthDb <= 0 || !speech.length) return [];
  const low = Math.pow(10, -d.depthDb / 20);
  const a = Math.max(0, d.attackMs), h = Math.max(0, d.holdMs), r = Math.max(0, d.releaseMs);
  // ducked spans: from the end of the attack ramp (= speech start) to the end of the hold
  const spans = merge(speech.map((s) => ({ startMs: s.startMs, endMs: s.endMs + h })), a + r);
  const keys: GainKey[] = [];
  for (const s of spans) {
    keys.push([r2(s.startMs - a), 1], [r2(s.startMs), low], [r2(s.endMs), low], [r2(s.endMs + r), 1]);
  }
  void durationMs;
  return keys.map(([t, g]) => [t, Math.round(g * 1e6) / 1e6]);
}

/** Fade in / out keys; the two fades are shortened proportionally so they never overlap. */
export function fadeKeys(durationMs: number, fadeInMs: number, fadeOutMs: number): GainKey[] {
  let fi = Math.max(0, fadeInMs), fo = Math.max(0, fadeOutMs);
  if (fi + fo > durationMs && fi + fo > 0) {
    const k = durationMs / (fi + fo);
    fi *= k;
    fo *= k;
  }
  const keys: GainKey[] = [];
  keys.push([0, fi > 0 ? 0 : 1]);
  if (fi > 0) keys.push([r2(fi), 1]);
  if (fo > 0) keys.push([r2(durationMs - fo), 1], [r2(durationMs), 0]);
  else keys.push([r2(durationMs), 1]);
  return keys;
}

export function buildMusicPlan(m: MusicSettings | undefined, durationMs: number, speechOut: TimeRange[]): MusicPlan | undefined {
  if (!m || !m.enabled || !m.path) return undefined;
  return {
    path: m.path,
    volumeDb: m.volumeDb,
    loop: m.loop,
    startMs: m.startMs,
    speech: speechOut,
    duck: duckKeys(speechOut, durationMs, m.duck),
    fade: fadeKeys(durationMs, m.fadeInMs, m.fadeOutMs),
  };
}

/**
 * Linear gain that puts music of integrated loudness `musicLufs` at `volumeDb` relative to speech of
 * `speechLufs` (fallback `refLufs` when the speech has no measurable loudness). Silent music: 0.
 * Capped at +30 dB so a near-silent file is never blown up.
 */
export function musicLevelGain(speechLufs: number, musicLufs: number, volumeDb: number, refLufs = -16): number {
  if (!Number.isFinite(musicLufs)) return 0;
  const ref = Number.isFinite(speechLufs) ? speechLufs : refLufs;
  return Math.pow(10, Math.min(30, ref + volumeDb - musicLufs) / 20);
}

/** Position in the music file (ms) for output time t; null after the end of an unlooped file. */
export function musicFileMs(m: Pick<MusicPlan, "loop" | "startMs">, t: number, fileMs: number): number | null {
  if (fileMs <= 0) return null;
  const p = m.startMs + t;
  if (m.loop) return ((p % fileMs) + fileMs) % fileMs;
  return p < fileMs ? p : null;
}

/**
 * Multiply `out[i]` (i = 0..n-1) by the envelope at t0 + i * dt (ms): one forward pass, so long
 * exports evaluate the keys in O(samples + keys). `stride` = channels for interleaved data.
 */
export function applyEnvelope(keys: GainKey[], t0: number, dt: number, out: Float32Array, stride = 1): void {
  const n = Math.floor(out.length / stride);
  if (!keys.length) return;
  let j = 0;
  for (let i = 0; i < n; i++) {
    const t = t0 + i * dt;
    while (j < keys.length && keys[j]![0] < t) j++;
    let g: number;
    if (j === 0) g = keys[0]![1];
    else if (j >= keys.length) g = keys[keys.length - 1]![1];
    else {
      const [ta, ga] = keys[j - 1]!;
      const [tb, gb] = keys[j]!;
      g = tb > ta ? ga + ((gb - ga) * (t - ta)) / (tb - ta) : gb;
    }
    for (let c = 0; c < stride; c++) out[i * stride + c]! *= g;
  }
}
